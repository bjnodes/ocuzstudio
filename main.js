function getProjectTitle(project) {
  return currentLanguage === "ko" ? projectTitlesKo[project.num] || project.title : project.title;
}

function getProjectPreviewImage(project) {
  if (!project || !project.gallery || !project.gallery.length) {
    return project?.img || "";
  }

  return (
    project.gallery.find((url) => url.includes("/source/")) ||
    project.gallery.find((url) => url.includes("/1400_still/")) ||
    project.gallery.find((url) => url.includes("/1400/")) ||
    project.gallery[0] ||
    project.img
  );
}

function applyStaticTranslations() {
  document.documentElement.lang = currentLanguage === "ko" ? "ko" : "en";

  document.querySelectorAll("[data-en][data-ko]").forEach((node) => {
    const value = currentLanguage === "ko" ? node.dataset.ko : node.dataset.en;

    if (node.dataset.i18nHtml === "true") {
      node.innerHTML = value;
    } else {
      node.textContent = value;
    }
  });

  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.setLang === currentLanguage);
  });
}

function renderStrip() {
  if (!strip) {
    return;
  }

  strip.innerHTML = "";

  projects.forEach((project) => {
    const previewImage = getProjectPreviewImage(project);
    const item = document.createElement("div");
    item.className = "thumb-item";
    item.innerHTML = `
      <div class="thumb-num">${project.num}</div>
      <img class="thumb-img" src="${previewImage}" alt="${getProjectTitle(project)}" loading="lazy" decoding="async">
      <div class="thumb-title">${getProjectTitle(project)}</div>
    `;
    item.addEventListener("click", () => openLightbox(project));
    strip.appendChild(item);
  });
}

function initStripMotion() {
  if (!strip || stripMotionBound) {
    return;
  }

  const stripViewport = strip.closest(".strip");

  if (!stripViewport) {
    return;
  }

  stripMotionBound = true;

  let animationFrame = null;
  let currentVelocity = 0;
  let targetVelocity = 0;

  const edgeRatio = 0.2;
  const maxVelocity = 22;
  const easing = 0.12;

  const stopAnimation = () => {
    targetVelocity = 0;
  };

  const tick = () => {
    currentVelocity += (targetVelocity - currentVelocity) * easing;

    if (Math.abs(currentVelocity) > 0.05) {
      stripViewport.scrollLeft += currentVelocity;
      animationFrame = window.requestAnimationFrame(tick);
      return;
    }

    currentVelocity = 0;
    animationFrame = null;
  };

  const ensureAnimation = () => {
    if (!animationFrame) {
      animationFrame = window.requestAnimationFrame(tick);
    }
  };

  stripViewport.addEventListener("mousemove", (event) => {
    const bounds = stripViewport.getBoundingClientRect();
    const x = event.clientX - bounds.left;
    const edgeWidth = bounds.width * edgeRatio;

    if (x < edgeWidth) {
      const intensity = 1 - x / edgeWidth;
      targetVelocity = -maxVelocity * intensity * intensity;
    } else if (x > bounds.width - edgeWidth) {
      const intensity = (x - (bounds.width - edgeWidth)) / edgeWidth;
      targetVelocity = maxVelocity * intensity * intensity;
    } else {
      targetVelocity = 0;
    }

    ensureAnimation();
  });

  stripViewport.addEventListener("mouseleave", stopAnimation);
  stripViewport.addEventListener("mouseenter", ensureAnimation);
}

function renderGrid() {
  if (!grid) {
    return;
  }

  grid.innerHTML = "";
  grid.setAttribute("data-grid-mode", "portfolio");

  projects.forEach((project) => {
    const previewImage = getProjectPreviewImage(project);
    const item = document.createElement("button");
    item.className = "grid-item";
    item.type = "button";
    item.setAttribute("aria-label", `${getProjectTitle(project)} gallery open`);
    item.innerHTML = `<img src="${previewImage}" alt="${getProjectTitle(project)}" loading="lazy" decoding="async">`;
    item.addEventListener("click", () => openLightbox(project));
    grid.appendChild(item);
  });
}

function renderLightbox() {
  if (!lightbox || !lightboxImage || !activeProject || !activeProject.gallery.length) {
    return;
  }

  const prevImage = activeProject.gallery[activeIndex - 1] || "";
  const nextImage = activeProject.gallery[activeIndex + 1] || "";

  lightboxTitle.textContent = getProjectTitle(activeProject);
  lightboxCount.textContent = `${String(activeIndex + 1).padStart(2, "0")} / ${String(activeProject.gallery.length).padStart(2, "0")}`;
  lightboxImage.src = activeProject.gallery[activeIndex];
  lightboxImage.alt = `${getProjectTitle(activeProject)} ${activeIndex + 1}`;

  if (lightboxPeekPrev && lightboxPeekImagePrev) {
    lightboxPeekImagePrev.src = prevImage;
    lightboxPeekImagePrev.alt = prevImage ? `${getProjectTitle(activeProject)} ${activeIndex}` : "";
    lightboxPeekPrev.classList.toggle("is-visible", Boolean(prevImage));
  }

  if (lightboxPeekNext && lightboxPeekImageNext) {
    lightboxPeekImageNext.src = nextImage;
    lightboxPeekImageNext.alt = nextImage ? `${getProjectTitle(activeProject)} ${activeIndex + 2}` : "";
    lightboxPeekNext.classList.toggle("is-visible", Boolean(nextImage));
  }

  if (lightboxPrev) {
    lightboxPrev.disabled = activeIndex === 0;
  }
  if (lightboxNext) {
    lightboxNext.disabled = activeIndex === activeProject.gallery.length - 1;
  }
}

function openLightbox(project) {
  if (!lightbox || !lightboxImage || !project.gallery.length) {
    return;
  }

  activeProject = project;
  activeIndex = 0;
  renderLightbox();
  lightbox.classList.add("is-open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-lightbox-open");
}

function closeLightbox() {
  if (!lightbox) {
    return;
  }

  lightbox.classList.remove("is-open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.classList.remove("is-lightbox-open");
}

function stepLightbox(direction) {
  if (!activeProject || !lightbox) {
    return;
  }
  const nextIndex = activeIndex + direction;
  if (nextIndex < 0 || nextIndex >= activeProject.gallery.length) {
    return;
  }

  lightbox.classList.remove("is-moving-prev", "is-moving-next", "is-animating");
  if (lightboxAnimationTimer) {
    window.clearTimeout(lightboxAnimationTimer);
  }
  void lightbox.offsetWidth;
  lightbox.classList.add("is-animating", direction > 0 ? "is-moving-next" : "is-moving-prev");

  activeIndex = nextIndex;
  renderLightbox();

  lightboxAnimationTimer = window.setTimeout(() => {
    lightbox.classList.remove("is-moving-prev", "is-moving-next", "is-animating");
    lightboxAnimationTimer = null;
  }, 360);
}

function setLanguage(lang) {
  currentLanguage = lang;
  window.localStorage.setItem("siteLanguage", lang);
  applyStaticTranslations();
  renderStrip();
  renderGrid();
  renderLightbox();
}

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.setLang));
});

if (lightbox && lightboxClose) {
  lightboxClose.addEventListener("click", closeLightbox);
  if (lightboxPrev) lightboxPrev.addEventListener("click", () => stepLightbox(-1));
  if (lightboxNext) lightboxNext.addEventListener("click", () => stepLightbox(1));
  if (lightboxPeekPrev) lightboxPeekPrev.addEventListener("click", () => stepLightbox(-1));
  if (lightboxPeekNext) lightboxPeekNext.addEventListener("click", () => stepLightbox(1));

  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) {
      closeLightbox();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (!lightbox.classList.contains("is-open")) {
      return;
    }

    if (event.key === "Escape") {
      closeLightbox();
    }
    if (event.key === "ArrowLeft") {
      stepLightbox(-1);
    }
    if (event.key === "ArrowRight") {
      stepLightbox(1);
    }
  });
}

